def fitness_function(particle, X_train, X_test, y_train, y_test):

    selected = particle.astype(bool)
    if np.sum(selected) == 0:
        return np.inf, 0, 0, 0

    X_train_selected = X_train.loc[:, selected]
    X_test_selected = X_test.loc[:, selected]

    knn = KNeighborsClassifier(n_neighbors=5)
    knn.fit(X_train_selected, y_train)


    predictions = knn.predict(X_test_selected)

    accuracy = accuracy_score(y_test, predictions)
    macro_f1 = f1_score(y_test, predictions, average="macro")

    num_selected = np.sum(selected)

    penalty = 0.1 * (num_selected / num_features)

    fitness = -((accuracy + macro_f1) / 2) + penalty

    return fitness, accuracy, macro_f1, num_selected


