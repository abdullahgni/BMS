# -----------------------------------
# Binary POA Main Loop
# -----------------------------------

for iteration in range(max_iterations):

    # Population mean (Equation 30)
    mean_position = np.mean(positions, axis=0)

    for i in range(num_parrots):

        current = positions[i].copy()

        # Randomly choose one of four behaviours
        behaviour = np.random.randint(4)

        # -------------------------------------------------
        # 1. FORAGING (Equation 29)
        # -------------------------------------------------

        if behaviour == 0:

            levy = levy_flight(num_features)

            r = np.random.rand()

            decay = (1 - iteration / max_iterations) ** (
                (2 * iteration) / max_iterations
            )

            new_position = (
                (current - best_position) * levy
                + r * decay * mean_position
            )

        # -------------------------------------------------
        # 2. PERCHING (Equation 32)
        # -------------------------------------------------

        elif behaviour == 1:

            levy = levy_flight(num_features)

            new_position = (
                current
                + best_position * levy
                + np.random.rand(num_features)
            )

        # -------------------------------------------------
        # 3. COMMUNICATION (Equation 33)
        # -------------------------------------------------

        elif behaviour == 2:

            P = np.random.rand()

            if P <= 0.5:

                new_position = (
                    0.2
                    * np.random.rand()
                    * (1 - iteration / max_iterations)
                    * (current - mean_position)
                )

            else:

                denominator = (
                    np.random.rand() * max_iterations + 1e-10
                )

                new_position = (
                    0.2
                    * np.random.rand()
                    * np.exp(-iteration / denominator)
                ) * np.ones(num_features)

        # -------------------------------------------------
        # 4. FEAR OF STRANGERS (Equation 34)
        # -------------------------------------------------

        else:

            r1 = np.random.rand()

            r2 = np.random.rand()

            term1 = (
                r1
                * np.cos(
                    0.5
                    * np.pi
                    * iteration
                    / max_iterations
                )
                * (best_position - current)
            )

            term2 = (
                np.cos(r2 * np.pi)
                * (
                    iteration
                    / max_iterations
                ) ** (
                    2 * iteration / max_iterations
                )
                * (current - best_position)
            )

            new_position = current + term1 - term2

        # ---------------------------------------------
        # Keep inside search space
        # ---------------------------------------------

        new_position = np.clip(
            new_position,
            lower_bound,
            upper_bound
        )

        positions[i] = new_position

        # ---------------------------------------------
        # Binary Conversion
        # ---------------------------------------------

        binary_position = (
            positions[i] > 0.5
        ).astype(int)

        fitness, accuracy, macro_f1, num_selected = fitness_function(
            binary_position,
            X_train,
            X_test,
            y_train,
            y_test
        )

